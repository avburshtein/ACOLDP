/**
 * Типографика UI: висячие предлоги, союзы и частицы не должны отрываться
 * от следующего слова при переносе строки — после них ставится неразрывный
 * пробел (\u00A0). Применять к статичным UI-текстам (описания режимов,
 * подсказки, баннеры), НЕ к содержимому артефактов.
 */
const HANGING_WORD =
  /(^|[\s(«„"'—–-])(в|во|с|со|к|ко|по|на|за|из|изо|от|ото|до|у|о|об|обо|и|а|но|или|либо|не|ни|для|без|безо|над|надо|под|подо|про|при|что|чем|как|же|ли|бы)([ \t])/g;

/** Тире не должно начинать строку — клеим его к предыдущему слову */
const HANGING_DASH = /([^\s—–])[ \t](—|–)(?=\s|$)/g;

export function noHanging(text: string): string {
  return text
    .replace(HANGING_WORD, (_m, prefix: string, word: string) => `${prefix}${word}\u00A0`)
    .replace(HANGING_DASH, '$1\u00A0$2');
}
